/** Browser checks: node scripts/check.mjs http://localhost:3000  (needs `playwright`) */
import { chromium } from 'playwright'
const base = (process.argv[2] || 'http://localhost:3000').replace(/\/$/, '')
const res = []
const check = (n, ok, d = '') => { res.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${d ? ' — ' + d : ''}`) }
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
for (const [label, vp] of [['desktop', { width: 1440, height: 900 }], ['tablet', { width: 820, height: 1180 }], ['mobile', { width: 390, height: 844 }]]) {
  const p = await b.newPage({ viewport: vp })
  const errs = []
  p.on('pageerror', (e) => errs.push(e.message))
  p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  const r = await p.goto(base + '/', { waitUntil: 'networkidle' })
  check(`[${label}] page loads`, r?.status() === 200)
  await p.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 500) { scrollTo(0, y); await new Promise((r) => setTimeout(r, 50)) } })
  check(`[${label}] no horizontal overflow`, (await p.evaluate(() => document.documentElement.scrollWidth - innerWidth)) <= 0)
  check(`[${label}] no JavaScript errors`, errs.length === 0, errs.slice(0, 2).join(' | '))
  await p.close()
}
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
await p.goto(base + '/', { waitUntil: 'networkidle' })
const html = await p.content()
check('no phone number published', !/\+?971\s?50\s?662|6621641|wa\.me/.test(html))
check('email published', html.includes('mridiniangurana@gmail.com'))
check('no photo on the page', (await p.$$('img')).length === 0)
const text = await p.evaluate(() => document.body.innerText)
for (const f of ['BSc (Hons) Psychology with Human Resource Management', 'Middlesex University Dubai', 'Expected 2028', 'Resource and Talent Management', 'Management in Global Environment', 'Brain, Body & Mind', 'Psychological Science', 'Database Systems', 'Computer Networks', 'Digital Design', 'BMS Solutions', 'outbound cold calls', 'IT and technology services', 'GTIS Cyber Security', 'Gurgaon, Haryana, India', 'debugging software applications', '3rd Best Speaker', 'BEHES 2020', 'JASHN 2024', 'basketball', 'fashion, dance and music', 'Java', 'SQL'])
  check(`resume fact present: ${f}`, text.includes(f))
for (const a of await p.$$eval('a[href^="#"]', (as) => [...new Set(as.map((a) => a.getAttribute('href')))])) if (a.length > 1) check(`anchor ${a} exists`, Boolean(await p.$(a)))
const pdf = await p.request.get(base + '/resume/Mridini-Angurana-Resume.pdf')
check('resume PDF downloads', pdf.status() === 200 && /pdf/.test(pdf.headers()['content-type'] || ''))
await p.waitForTimeout(2500)
check('3D network initialises', ['ready', 'unavailable'].includes(await p.$eval('[data-webgl]', (e) => e.dataset.webgl)))
await p.getByRole('button', { name: 'Adaptability' }).click(); await p.waitForTimeout(1500)
check('trait button highlights its hub', (await p.$eval('[data-webgl]', (e) => e.dataset.active)) === '4' && (await p.getByRole('button', { name: 'Adaptability' }).getAttribute('aria-pressed')) === 'true')
await p.close()
const m = await b.newPage({ viewport: { width: 390, height: 844 } })
await m.goto(base + '/', { waitUntil: 'networkidle' })
await m.getByRole('button', { name: 'Open menu' }).click()
await m.locator('#menu').getByRole('link', { name: 'Skills' }).click()
await m.waitForTimeout(1200)
check('mobile menu navigates and closes', (await m.locator('#menu').count()) === 0 && (await m.evaluate(() => location.hash)) === '#skills')
await m.close()
const rm = await b.newPage({ viewport: { width: 1280, height: 800 } })
await rm.emulateMedia({ reducedMotion: 'reduce' })
const rmErr = []
rm.on('pageerror', (e) => rmErr.push(e.message))
rm.on('console', (x) => x.type() === 'error' && rmErr.push(x.text()))
await rm.goto(base + '/', { waitUntil: 'networkidle' })
await rm.waitForTimeout(1500)
check('reduced motion: no errors', rmErr.length === 0, rmErr.join(' | '))
check('reduced motion: content visible', await rm.getByRole('heading', { name: 'Beyond the classroom' }).isVisible())
await b.close()
const failed = res.filter((x) => !x).length
console.log(`\n${res.length - failed}/${res.length} checks passed`)
process.exit(failed ? 1 : 0)
